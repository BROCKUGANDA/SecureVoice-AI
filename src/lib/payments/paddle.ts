import "server-only";
/**
 * Paddle adapter — implements the `PaymentProvider` port from `./provider`.
 *
 * Everything Paddle-shaped stops at this file. The only things that cross the
 * boundary are port types. A caller must never be able to tell which gateway is
 * behind a checkout.
 *
 * ## Four rules this implementation exists to enforce
 *
 *   1. **HMAC-SHA256 over `ts + ":" + the RAW BYTES`, from a caller-supplied
 *      timestamp.** Paddle signs `` `${ts}:${rawBody}` `` where `ts` is the value
 *      in the signature header itself, not `Date.now()`. Two classic bugs are
 *      structurally impossible here and each is covered by a negative test:
 *        - signing over the body alone (the `ts:` prefix dropped);
 *        - `JSON.parse` then `JSON.stringify` before hashing — a re-serialised
 *      body changes key order and whitespace and MUST be rejected. So
 *      `verifyWebhook` takes a `Buffer` and never re-serialises.
 *      A stale `ts` is refused on its own tolerance window, which is what stops
 *      a captured-and-replayed webhook from settling twice.
 *   2. **A webhook is a CLAIM, not a fact.** `verifyWebhook` proves the bytes
 *      came from Paddle. It does not prove the money moved. Settlement is
 *      `settlePayment`'s job and is guarded by its own idempotency.
 *   3. **Our reference is generated by us**, never accepted from a client, and
 *      it rides to Paddle in `custom_data` so the webhook can hand it back.
 *   4. **Checkout is PRICE-DRIVEN, which is the hard impedance mismatch here.**
 *      The port's `CheckoutRequest` carries a `Money` (an amount); Paddle will
 *      only accept a `priceId` it already knows. So this adapter needs a price
 *      catalog, and a request whose amount matches no configured price is
 *      REFUSED with a loud error naming the missing key — never silently charged
 *      to a neighbouring tier. Getting that wrong bills a customer for the plan
 *      they did not choose, which is not a bug you find in staging.
 *
 * ## `chargeStoredAuthorization` is NOT SUPPORTED, and that is deliberate
 *
 * The port member exists to charge computed overage against a card authorization
 * captured earlier. Paddle is a Merchant of Record: there is no stored card
 * authorization, no vault, and no way to take a payment later against a prior
 * consent. This is a gap in Paddle's product, not in this implementation.
 *
 * So the method returns a refusal naming the reason rather than pretending. The
 * alternative — implementing it with a subscription and a usage meter — would be
 * a different billing model wearing this one's interface, and `overage.ts` would
 * need rewriting rather than just re-pointing. Fail loudly; decide deliberately.
 *
 * ## MoR changes what `amountMinor` means
 *
 * Paddle collects and remits sales tax, so a transaction's `unit_price` is
 * gross-of-tax in the *currency the buyer is charged in*, which may not be the
 * currency we priced in. Anything that assumes "charged == received" has to be
 * re-examined. `credits` are denominated in minor units in `provider.ts`, so a
 * customer buying GBP is credited GBP-minor units unless that is handled
 * upstream — see the `paddleCurrency` note on `createCheckout`.
 *
 * ## Sandbox guard
 *
 * The default key must start with `pdl_sdbx_`. A live key is refused unless
 * `PADDLE_ALLOW_LIVE_KEYS=1` is set explicitly, so this adapter cannot reach a
 * live gateway by accident — the same posture `paystack.ts` takes.
 *
 * ## No live network in tests
 *
 * The HTTP client is injected; every gate supplies a mock. `createPaddleProvider`
 * is the only construction path, so there is no global client to accidentally hit
 * the network from.
 */


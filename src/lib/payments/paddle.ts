/**
 * The single hidden product every negotiated, non-catalog price hangs off.
 *
 * Name, not id, is the handle: `paddle-verify.ts` and the pricing page both work
 * from the published tiers, and a negotiated one-off must never be reachable
 * from either. A deployment may pin the id in `PADDLE_NEGOTIATED_PRODUCT_ID` to
 * skip the lookup; otherwise it is found by name before it is created.
 */
export const NEGOTIATED_PRODUCT_NAME = "Negotiated Terms";

/** Replay window. Paddle's own dashboard default is 5 minutes. */
export const SIGNATURE_TOLERANCE_SEC = Number(process.env.PADDLE_SIGNATURE_TOLERANCE_SEC) || 300;

/** The two hosts, in exactly the strings Paddle uses them. */
const SANDBOX_BASE_URL = "https://sandbox-api.paddle.com";
const PRODUCTION_BASE_URL = "https://api.paddle.com";

/**
 * The host is derived from the KEY, not from a default — for the same reason
 * `normalizeConfig` refuses an unrecognised prefix and `paddle-events.ts` picks
 * the SDK environment from `pdl_sdbx_`: the key is the one fact that cannot be
 * wrong about which account money moves in.
 *
 * The previous behaviour was `process.env.PADDLE_BASE_URL ??
 * "https://sandbox-api.paddle.com"`, and `PADDLE_BASE_URL` is declared in no env
 * file at all. A production deployment therefore sent every `POST /transactions`
 * to the sandbox, where the ids in `PADDLE_PRICES` do not exist — and a
 * production key answered with 401/404 rather than taking real money, which is
 * the only reason the mistake was survivable.
 */
function baseUrlForApiKey(apiKey: string): string {
  const derived = apiKey.startsWith("pdl_sdbx_") ? SANDBOX_BASE_URL : PRODUCTION_BASE_URL;
  const override = process.env.PADDLE_BASE_URL?.trim().replace(/\/+$/, "");
  if (!override) return derived;
  if (override !== derived) {
    throw new TypeError(
      `PADDLE_BASE_URL (${override}) does not match the environment of the key in ` +
        `${SECRET_KEY_ENV} (which requires ${derived}). One of the two is for a ` +
        `different Paddle account; refusing to bill the one you did not mean.`,
    );
  }
  return override;
}

// ── signature ─────────────────────────────────────────────────────────────────

/**
 * The `Paddle-Signature` header: `ts=<unix seconds>;h1=<hex hmac>`.
 *
 * Parsed rather than pattern-matched into the caller's code, because a malformed
 * header and a wrong digest are DIFFERENT failures and the port models them as
 * different reasons (`malformed_signature` vs `digest_mismatch`) — a caller
 * triaging a webhook queue needs to tell "someone sent us junk" apart from
 * "someone tampered with a real event".
 */
export type PaddleSignature = { ts: string; h1: string };

export function parseSignatureHeader(header: string): PaddleSignature | null {
  for (const part of header.split(";")) {
    const eq = part.indexOf("=");
    if (eq <= 0) continue;
    const key = part.slice(0, eq).trim();
    const value = part.slice(eq + 1).trim();
    if (key === "ts" && value !== "") return parseH1(header);
  }
  return null;
}

function parseH1(header: string): PaddleSignature | null {
  let ts = "";
  let h1 = "";
  for (const part of header.split(";")) {
    const eq = part.indexOf("=");
    if (eq <= 0) continue;
    const key = part.slice(0, eq).trim();
    const value = part.slice(eq + 1).trim();
    if (key === "ts") ts = value;
    else if (key === "h1") h1 = value;
  }
  if (ts === "" || h1 === "") return null;
  if (!/^\d+$/.test(ts)) return null;
  if (!/^[0-9a-fA-F]+$/.test(h1) || h1.length % 2 !== 0) return null;
  return { ts, h1: h1.toLowerCase() };
}

/**
 * `HMAC-SHA256(`${ts}:${rawBody}`, secret)` as lowercase hex, over the RAW
 * bytes. The `ts:` prefix is Paddle's and dropping it produces a digest that is
 * always wrong — which is the safe direction, but it must be right for the right
 * reason, so it is asserted directly rather than left to fall out of a passing
 * fixture.
 */
export function paddleDigest(rawBody: Buffer | string, secret: string, ts: string): string {
  const body = Buffer.isBuffer(rawBody) ? rawBody : Buffer.from(rawBody, "utf8");
  return createHmac("sha256", secret).update(`${ts}:`).update(body).digest("hex");
}

/** Constant-time compare, with the length check FIRST — `timingSafeEqual` throws on mismatch. */
export function digestMatches(expected: string, presented: string): boolean {
  const a = Buffer.from(expected, "hex");
  let b: Buffer;
  try {
    b = Buffer.from(presented, "hex");
  } catch {
    return false;
  }
  if (a.length === 0 || a.length !== b.length) return false;
  return timingSafeEqual(a, b);
}

/** Reject a replayed event. `now` is injected so this costs no wall-clock in tests. */
export function timestampFresh(ts: string, now: number = Date.now()): boolean {
  const seconds = Number(ts);
  if (!Number.isFinite(seconds)) return false;
  return Math.abs(now / 1000 - seconds) <= SIGNATURE_TOLERANCE_SEC;
}

// ── reference ─────────────────────────────────────────────────────────────────

/** Crockford base32 — same alphabet as the Paystack adapter's ULID. */
const ULID_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";

/** Monotonic ULID: 48-bit ms timestamp + 80 bits of randomness. */
export function ulid(now: number = Date.now()): string {
  let time = "";
  let t = now;
  for (let i = 0; i < 10; i++) {
    time = ULID_ALPHABET[t % 32] + time;
    t = Math.floor(t / 32);
  }
  // CSPRNG, not `Math.random()`: this 80 bits is the only thing separating one
  // payment reference from the next, and `buildReference()` hands the result to
  // the gateway as the merchant-side id a webhook is matched on. A V8 xorshift
  // seeded by the process start is reconstructible from two nearby references,
  // which is why src/lib/ids.ts exists and names it. Same fix, same file, for
  // the reference that authorises a charge.
  const buf = randomBytes(16);
  let random = "";
  for (const byte of buf) random = ULID_ALPHABET[byte % 32] + random;
  return (time + random).slice(0, 26);
}

function sanitizeSegment(value: string, max: number): string {
  return value.replace(/[^A-Za-z0-9_-]/g, "").slice(0, max);
}

/** `org_{orgId}_{purpose}_{ulid}` — ours, never accepted from a client. */
export function buildReference(orgId: string, purpose: string): string {
  const org = sanitizeSegment(orgId, 40);
  const why = sanitizeSegment(purpose, 24) || "topup";
  if (org === "") throw new TypeError("orgId is required to build a payment reference");
  return `org_${org}_${why}_${ulid()}`;
}

export function parseReference(reference: string): { orgId: string; purpose: string } | null {
  const m = /^org_([A-Za-z0-9_-]{1,40})_([A-Za-z0-9_-]{1,24})_[0-9A-Z]{26}$/.exec(reference);
  if (!m) return null;
  return { orgId: m[1]!, purpose: m[2]! };
}

// ── price catalog ─────────────────────────────────────────────────────────────

/**
 * Canonical key for a configured price: `<currency>_<minor>_<interval>`.
 *
 * `interval` is `month`, `year` or `once`. Lower-case currency, integer minor
 * units — the two things Paddle itself treats as significant, and the two that
 * make a typo fail loudly instead of resolving to a real, wrong price.
 */
export function priceKey(
  money: { amountMinor: number; currency: string },
  interval: "month" | "year" | "once",
): string {
  return `${money.currency.toLowerCase()}_${money.amountMinor}_${interval}`;
}

export type PaddlePriceMap = Record<string, string>;

/**
 * Read the price map from `PADDLE_PRICES`.
 *
 * A JSON object rather than one env var per tier: twenty-odd vars is a config
 * surface nobody can review, and the whole point of the map is that the amount
 * and the `pri_` id are checked against each other in one place.
 */
export function parsePriceMap(raw: string | undefined): PaddlePriceMap {
  if (!raw || raw.trim() === "") return {};
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    throw new TypeError(`${PRICES_ENV} is not valid JSON`);
  }
  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new TypeError(`${PRICES_ENV} must be a JSON object of priceKey -> pri_...`);
  }
  const out: PaddlePriceMap = {};
  for (const [k, v] of Object.entries(parsed as Record<string, unknown>)) {
    if (typeof v !== "string" || !/^pri_[A-Za-z0-9]+$/.test(v)) {
      throw new TypeError(`${PRICES_ENV}["${k}"] must be a Paddle price id (pri_...)`);
    }
    out[k] = v;
  }
  return out;
}

// ── event decoding ────────────────────────────────────────────────────────────

/**
 * Map a verified Paddle event onto the port's `ProviderEvent`.
 *
 * Only the events that correspond to a `kind` the port models are accepted;
 * everything else returns null and surfaces as `unsupported_event` rather than
 * being decoded into a guess. `subscription.*` events are deliberately NOT
 * mapped: the port's `kind` is about money, and a subscription state change is
 * not a charge. Mapping one onto the other would credit a wallet on a plan
 * change.
 */
export function decodePaddleEvent(payload: Record<string, unknown>): ProviderEvent | null {
  const eventId = typeof payload.event_id === "string" ? payload.event_id : "";
  const eventType = typeof payload.event_type === "string" ? payload.event_type : "";
  if (eventId === "" || eventType === "") return null;

  const data = payload.data;
  if (!data || typeof data !== "object") return null;
  const d = data as Record<string, unknown>;

  const custom = d.custom_data;
  const reference =
    custom &&
    typeof custom === "object" &&
    typeof (custom as { reference?: unknown }).reference === "string"
      ? (custom as { reference: string }).reference
      : "";
  // A reference we did not mint is not ours to settle. Without this a Paddle
  // event carrying someone else's `custom_data` would be credited to an org.
  if (reference === "" || parseReference(reference) === null) return null;

  const items = Array.isArray(d.items) ? (d.items as Record<string, unknown>[]) : [];
  const first = items[0];
  if (!first) return null;
  const unit = first.unit_price as { amount?: unknown; currency_code?: unknown } | undefined;
  const amountMinor = Number(unit?.amount);
  const currency = typeof unit?.currency_code === "string" ? unit.currency_code : "";
  if (!Number.isInteger(amountMinor) || amountMinor <= 0 || !/^[A-Za-z]{3}$/.test(currency)) {
    return null;
  }

  const occurredAt =
    typeof d.occurred_at === "string"
      ? d.occurred_at
      : typeof d.completed_at === "string"
        ? d.completed_at
        : new Date().toISOString();

  let kind: ProviderEvent["kind"];
  if (eventType === "transaction.completed") kind = "charge.succeeded";
  else if (eventType === "transaction.failed") kind = "charge.failed";
  else if (eventType === "transaction.refunded") kind = "refund.succeeded";
  else return null;

  return {
    eventId,
    kind,
    reference,
    money: { amountMinor, currency: currency.toUpperCase() },
    occurredAt,
    metadata: {
      paddleTransactionId: typeof d.id === "string" ? d.id : "",
      eventType,
      status: typeof d.status === "string" ? d.status : "",
    },
  };
}

// ── HTTP ──────────────────────────────────────────────────────────────────────

export type HttpClient = (url: string, init: RequestInit) => Promise<Response>;

export type PaddleConfig = {
  apiKey: string;
  webhookSecret: string;
  prices: PaddlePriceMap;
  baseUrl?: string;
  /**
   * Injected in every gate. Defaults to `globalThis.fetch` inside
   * `normalizeConfig`, so a production call site does not have to write it.
   */
  http?: HttpClient;
};

function normalizeConfig(cfg: PaddleConfig): Required<
  Omit<PaddleConfig, "apiKey" | "webhookSecret">
> & {
  apiKey: string;
  webhookSecret: string;
  prices: PaddlePriceMap;
} {
  const apiKey = cfg.apiKey?.trim() ?? "";
  if (apiKey === "") throw new TypeError(`${SECRET_KEY_ENV} is required`);

  const live = apiKey.startsWith("pdl_live_");
  const sandbox = apiKey.startsWith("pdl_sdbx_");
  if (!live && !sandbox) {
    throw new TypeError(
      `${SECRET_KEY_ENV} does not look like a Paddle key (expected a "pdl_sdbx_" or "pdl_live_" prefix)`,
    );
  }
  if (live && process.env[PADDLE_ALLOW_LIVE_ENV] !== "1") {
    throw new TypeError(
      `refusing a LIVE Paddle key: set ${PADDLE_ALLOW_LIVE_ENV}=1 to allow it deliberately. ` +
        `This guard exists so a mis-set environment cannot take real money.`,
    );
  }

  const webhookSecret = cfg.webhookSecret?.trim() ?? "";
  if (webhookSecret === "") throw new TypeError(`${WEBHOOK_SECRET_ENV} is required`);

  return {
    apiKey,
    webhookSecret,
    prices: cfg.prices ?? {},
    baseUrl: cfg.baseUrl ?? baseUrlForApiKey(apiKey),
    http: cfg.http ?? ((url, init) => fetch(url, init)),
  };
}

type Resolved = ReturnType<typeof normalizeConfig>;

async function paddleRequest<T>(
  cfg: Resolved,
  method: "GET" | "POST",
  path: string,
  body?: unknown,
): Promise<{ ok: true; value: T } | { ok: false; error: string }> {
  let res: Response;
  try {
    res = await cfg.http(`${cfg.baseUrl}${path}`, {
      method,
      headers: {
        // Bearer, measured against the sandbox on 2026-10-14:
        //   `Authorization: Basic base64("<key>:")` → HTTP 403
        //       {"error":{"code":"authentication_malformed","detail":"Authentication
        //        header included, but incorrectly formatted."}}
        //   `Authorization: Bearer <key>`           → HTTP 200 with the catalog body.
        //
        // This file used to assert the opposite — that Paddle takes the key as a
        // Basic username with an empty password, and that the Basic form was the
        // reason a probe failed while the SDK worked. Both halves of that sentence
        // are inverted: the SDK sends Bearer, and it was the hand-rolled Basic call
        // that 403'd. Every REST operation behind this function was therefore dead
        // — `createCheckout`, `createInvoice` and `refund` all returned
        // `http_403:authentication_malformed` — while the webhook path stayed
        // healthy because it goes through the SDK. That asymmetry is the reason the
        // bug survived: the surface that received money worked, the surface that
        // raised documents did not.
        Authorization: `Bearer ${cfg.apiKey}`,
        "Content-Type": "application/json",
        Accept: "application/json",
      },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    });
  } catch (e) {
    return { ok: false, error: `network_error:${e instanceof Error ? e.message : "unknown"}` };
  }

  const text = await res.text().catch(() => "");
  if (!res.ok) {
    // Paddle's error envelope is `{ code, message }`. Surfacing the code matters:
    // 401 means the key, 403 means permissions on that resource, and they have
    // completely different fixes.
    let detail = `http_${res.status}`;
    try {
      const parsed = JSON.parse(text) as { code?: string; message?: string };
      if (parsed?.code) detail = `http_${res.status}:${parsed.code}`;
    } catch {
      /* non-JSON error body — the status alone is the signal */
    }
    return { ok: false, error: detail };
  }
  if (text === "") return { ok: true, value: {} as T };
  try {
    return { ok: true, value: JSON.parse(text) as T };
  } catch {
    return { ok: false, error: "malformed_response" };
  }
}

function headerValue(
  headers: Record<string, string | string[] | undefined>,
  name: string,
): string | undefined {
  const v = headers[name] ?? headers[name.toLowerCase()];
  if (Array.isArray(v)) return v[0];
  return v ?? undefined;
}

// ── provider ──────────────────────────────────────────────────────────────────

type TransactionResponse = {
  data?: {
    id?: string;
    checkout?: { url?: string };
    custom_data?: { reference?: string };
  };
};

/**
 * The buyer block, transcribed and never invented.
 *
 * Paddle is Merchant of Record, so it charges VAT/GST where the BUYER is: the
 * registered address and tax number on this document are the customer's facts,
 * not ours. Nothing here defaults a country, borrows the deployment's address,
 * or treats a missing tax number as a zero-rate signal — guessing a buyer's
 * jurisdiction under-charges a taxable bank, which is the precise failure a
 * Merchant-of-Record arrangement exists to prevent.
 *
 * The keys are Paddle's transaction `customer` shape (`company_name`,
 * `country_code`, `postal_code`, `tax_identifiers[]`), verified against the
 * sandbox rather than assumed from the older `name` / flat `tax_id` spelling
 * this file used before it had ever received a 2xx here.
 */
function invoiceCustomer(req: InvoiceRequest): Record<string, unknown> {
  const email = (req.customer?.email ?? "").trim();
  const company = (req.customer?.name ?? "").trim();
  const addr = req.customer?.address ?? {};
  const country = (addr["country_code"] ?? "").trim().toUpperCase();
  const postal = (addr["postal_code"] ?? "").trim();
  const taxId = (req.taxId ?? "").trim();
  if (!email && !company && !country && !postal && !taxId) return {};
  return {
    customer: {
      ...(email ? { email } : {}),
      ...(company ? { company_name: company.slice(0, 160) } : {}),
      ...(country ? { country_code: country } : {}),
      ...(postal ? { postal_code: postal.slice(0, 16) } : {}),
      ...(taxId
        ? {
            tax_identifiers: [
              { type: process.env.PADDLE_TAX_ID_TYPE ?? "eu_vat", value: taxId.slice(0, 64) },
            ],
          }
        : {}),
    },
  };
}

export function createPaddleProvider(cfg: PaddleConfig): PaymentProvider {
  const c = normalizeConfig(cfg);

  /**
   * `POST /transactions` — Paddle's hosted checkout.
   *
   * `collectionMode: "automatic"` means Paddle charges the saved/default method
   * without a further confirmation step, which is what makes the webhook the
   * only settlement signal we have. "manual" would require an explicit capture
   * call this adapter deliberately does not make.
   */
  async function createCheckout(req: CheckoutRequest): Promise<CheckoutSession> {
    const money = assertMoney(req.money, "checkout.money");
    const reference = buildReference(req.orgId, req.purpose);

    // Which configured price is this amount? Refuse loudly rather than guess:
    // falling through to "the first price that fits" would bill a customer for
    // a tier they did not pick.
    const candidates: ("month" | "year")[] = ["month", "year"];
    const matches = candidates
      .map((interval) => {
        const key = priceKey(money, interval);
        const priceId = c.prices[key];
        return priceId ? { interval, priceId, key } : null;
      })
      .filter((m): m is { interval: "month" | "year"; priceId: string; key: string } => m !== null);

    if (matches.length === 0) {
      const wanted = candidates.map((i) => priceKey(money, i)).join(" or ");
      throw new Error(
        `paddle: no configured price matches this checkout (looked for "${wanted}"). ` +
          `Add it to ${PRICES_ENV}. Refusing to guess — charging a neighbouring tier is ` +
          `worse than failing.`,
      );
    }
    // Ambiguous if the same amount is configured for both intervals. Prefer
    // monthly (the common case) and say so, because silently picking yearly
    // would charge 10x for the same request.
    const chosen = matches.find((m) => m.interval === "month") ?? matches[0]!;

    // The plan this checkout buys, anchored NOW and carried to the webhook in
    // `custom_data`. Money never converts 1:1 into credits — the plan's
    // allowance is the unit count (#204) — and it must be decided at mint time,
    // not re-derived when the paid event arrives, because a first purchase has
    // no subscription row and a later plan change must not retroactively
    // re-rate this one.
    const { planFromPriceKey } = await import("@/lib/payments/overage");
    const plan = planFromPriceKey(chosen.key);
    const entitlements: StoredEntitlement[] = plan ? [{ key: `plan:${plan}` }] : [];

    const res = await paddleRequest<TransactionResponse>(c, "POST", "/transactions", {
      items: [{ price_id: chosen.priceId, quantity: 1 }],
      collection_mode: "automatic",
      custom_data: { reference, ...(entitlements.length > 0 ? { entitlements } : {}) },
      customer: { email: req.email },
      ...(req.returnUrl === undefined ? {} : { settings: { return_url: req.returnUrl } }),
    });
    if (!res.ok) throw new Error(`paddle: checkout failed (${res.error})`);

    const url = res.value.data?.checkout?.url ?? "";
    if (url === "") throw new Error("paddle: transaction created but no checkout url returned");
    // Paddle has no `access_code` concept; the field exists on the port for
    // Paystack's benefit. Empty is honest, and callers that need a token must
    // use `reference`, which is ours and stable.
    return { url, accessCode: "", reference };
  }

  /**
   * Mint one hidden, non-catalog price for a negotiated amount.
   *
   * Paddle is Merchant of Record, so EVERY charge must resolve to a priced
   * catalog line it can tax, invoice and report — measured against the sandbox
   * on 2026-10-14, a transaction item carrying an amount instead of a catalogued
   * price is refused outright:
   *   `items.0: price_id is required` (and `Must validate one and only one
   *    schema (oneOf)`), for BOTH `price:{amount_minor}` and `price:{amount}`.
   * So a negotiated figure is not sent as a number; it is minted as a one-off
   * price and then referenced. `POST /prices` itself requires `product_id` and
   * `description`, and `unit_price.amount` is a MINOR-UNIT STRING — the catalog
   * answers `"9900"` for $99.00, so a raw integer is a type error.
   *
   * The prices hang off a single hidden product, never off Starter/Growth/
   * Enterprise: those three are the published tiers, and a negotiated one-off
   * must not become a tier somebody can buy twice. The product is found by name
   * before it is created, so the hundredth invoice reuses the first invoice's
   * product rather than littering the catalog.
   */
  async function adHocPriceFor(
    money: { amountMinor: number; currency: string },
    description: string,
    reference: string,
  ): Promise<{ ok: true; priceId: string } | { ok: false; reason: string }> {
    const productId = await negotiatedProductId();
    if (!productId) return { ok: false, reason: "negotiated_product_unavailable" };

    const minted = await paddleRequest<{ data?: { id?: string } }>(c, "POST", "/prices", {
      product_id: productId,
      description:
        `SecureVoice negotiated one-off ${money.amountMinor} ${money.currency} — ${description}`.slice(
          0,
          250,
        ),
      unit_price: { amount: String(money.amountMinor), currency_code: money.currency },
      quantity: { minimum: 1, maximum: 1 },
    });
    if (!minted.ok) {
      await auditMoney({
        reference,
        actor: "gateway:paddle",
        intent: "price_adhoc_failed",
        detail: `ad-hoc price of ${money.amountMinor} ${money.currency} was refused: ${minted.error}`,
        meta: { amountMinor: money.amountMinor, currency: money.currency, description },
      });
      return { ok: false, reason: `ad_hoc_price_failed:${minted.error}` };
    }
    const priceId = (minted.value.data?.id ?? "").trim();
    if (priceId === "") return { ok: false, reason: "ad_hoc_price_returned_no_id" };
    // A successful mint leaves a sellable `price_id` for an arbitrary negotiated
    // amount on PADDLE's side, attached to no published tier and invisible to any
    // query we run afterwards. This row is the only durable record of it.
    await auditMoney({
      reference,
      actor: "gateway:paddle",
      intent: "price_adhoc_minted",
      detail: `minted one-off price ${priceId} for ${money.amountMinor} ${money.currency}`,
      meta: {
        priceId,
        productId,
        amountMinor: money.amountMinor,
        currency: money.currency,
        description,
      },
    });
    return { ok: true, priceId };
  }

  async function negotiatedProductId(): Promise<string> {
    const pinned = (process.env.PADDLE_NEGOTIATED_PRODUCT_ID ?? "").trim();
    if (pinned) return pinned;
    const listed = await paddleRequest<{ data?: { id?: string; name?: string }[] }>(
      c,
      "GET",
      "/products?per_page=100",
    );
    const existing = (listed.ok ? (listed.value.data ?? []) : []).find(
      (p) => (p.name ?? "").trim().toLowerCase() === NEGOTIATED_PRODUCT_NAME.toLowerCase(),
    );
    if (existing?.id) return existing.id;
    const created = await paddleRequest<{ data?: { id?: string } }>(c, "POST", "/products", {
      name: NEGOTIATED_PRODUCT_NAME,
      description:
        "Non-catalog one-off amounts raised on a negotiated enterprise invoice. Never listed on the pricing page.",
      tax_category: "saas",
      type: "custom",
    });
    return created.ok ? (created.value.data?.id ?? "") : "";
  }

  /**
   * Raise a manual-collection invoice for an enterprise deal.
   *
   * Paddle's route to a VAT/GST document with bank-transfer settlement is
   * `POST /transactions` with `collection_mode: "manual"`.
   *
   * The important property is what this does NOT do: it credits nothing.
   * `settledUnits: 0` is returned unconditionally, and that is a design
   * constraint rather than a limitation of the current implementation —
   * crediting an unpaid invoice would extend an unbounded credit line against a
   * customer's good faith. Units arrive only via `settlePayment`, on
   * `transaction.paid` or on dual-control operator confirmation.
   */
  async function createInvoice(req: InvoiceRequest): Promise<InvoiceResult> {
    if (req.items.length === 0) {
      return { ok: false, reference: req.reference, reason: "invoice_has_no_items" };
    }

    // Amounts are MINOR UNITS and must be positive integers — `assertMoney`
    // bounds them here AND again inside the minted price, because this is the
    // boundary where a negotiated figure becomes money.
    const items: { price_id: string; quantity: number }[] = [];
    for (const [index, item] of req.items.entries()) {
      const money = assertMoney(
        { amountMinor: item.amountMinor, currency: req.currency },
        `invoice.items[${index}]`,
      );
      const minted = await adHocPriceFor(money, item.description, req.reference);
      if (!minted.ok) return { ok: false, reference: req.reference, reason: minted.reason };
      // One unit per minted price: `quantity` on the price is pinned to 1, so a
      // line of N is expressed as N items rather than as a multiplier the
      // gateway might price differently.
      const quantity = item.quantity ?? 1;
      for (let n = 0; n < quantity; n++) items.push({ price_id: minted.priceId, quantity: 1 });
    }

    const res = await paddleRequest<TransactionResponse>(c, "POST", "/transactions", {
      items,
      // THE line that makes this an invoice rather than a checkout.
      collection_mode: "manual",
      // Measured: manual is refused with
      // `transaction_billing_details_object_required`, and the one member
      // Paddle demands inside it is `payment_terms`, in its FLAT form
      // `{interval, amount_due, frequency}` — nesting under `frequency` answers
      // `interval is required` / `frequency: Expected integer, given object`.
      // The previous body sent `due_date` instead, which Paddle does not accept
      // in place of payment terms.
      billing_details: {
        payment_terms: {
          interval: "day",
          amount_due: req.dueInDays ?? 30,
          frequency: 1,
        },
        ...(req.purchaseOrderNumber
          ? { purchase_order_number: req.purchaseOrderNumber.slice(0, 64) }
          : {}),
      },
      // OUR reference, so the paid webhook hands back something we can match.
      custom_data: { reference: req.reference },
      ...invoiceCustomer(req),
    });

    if (!res.ok) {
      // Surfaced as a refusal, not a throw: an enterprise sales flow needs to
      // show the operator WHY the invoice was not raised (403 = the key lacks
      // permission, 400 = a malformed custom price), not a 500.
      await auditMoney({
        reference: req.reference,
        ...(req.orgId ? { orgId: req.orgId } : {}),
        actor: req.recordedBy,
        intent: "invoice_issuance_failed",
        detail: `Paddle refused the invoice: ${res.error}`,
        meta: {
          reason: `paddle_invoice_failed:${res.error}`,
          currency: req.currency,
          lines: req.items.length,
          totalMinor: req.items.reduce((sum, i) => sum + i.amountMinor * (i.quantity ?? 1), 0),
        },
      });
      return { ok: false, reference: req.reference, reason: `paddle_invoice_failed:${res.error}` };
    }

    const invoiceId = res.value.data?.id ?? "";
    if (invoiceId === "") {
      await auditMoney({
        reference: req.reference,
        ...(req.orgId ? { orgId: req.orgId } : {}),
        actor: req.recordedBy,
        intent: "invoice_issuance_failed",
        detail: "Paddle returned no transaction id for the invoice",
        meta: { reason: "paddle_returned_no_transaction_id", currency: req.currency },
      });
      return { ok: false, reference: req.reference, reason: "paddle_returned_no_transaction_id" };
    }

    // The document exists at the gateway and is not in our database — Paddle
    // owns it from here. This row is the only place its id, amount and issuer
    // are recorded on our side of the boundary.
    await auditMoney({
      reference: req.reference,
      ...(req.orgId ? { orgId: req.orgId } : {}),
      actor: req.recordedBy,
      intent: "invoice_issued",
      detail: `manual-collection invoice ${invoiceId} issued for ${req.currency}`,
      meta: {
        invoiceId,
        currency: req.currency,
        lines: req.items.length,
        totalMinor: req.items.reduce((sum, i) => sum + i.amountMinor * (i.quantity ?? 1), 0),
        recordedBy: req.recordedBy,
        ...(req.dueInDays === undefined ? {} : { dueInDays: req.dueInDays }),
        ...(req.taxId ? { taxIdPresent: true } : {}),
        settledUnits: 0,
      },
    });

    return {
      ok: true,
      reference: req.reference,
      invoiceId,
      // `checkout.url` on a manual transaction is where the buyer settles —
      // card-on-invoice or a bank transfer — so it doubles as the payment link.
      ...(res.value.data?.checkout?.url ? { paymentLink: res.value.data.checkout.url } : {}),
      settledUnits: 0,
    };
  }

  return {
    id: PADDLE_PROVIDER_ID,

    createCheckout,

    createInvoice,

    /**
     * Paddle signs `ts:rawBody` with the notification-destination secret. Does
     * NOT settle — `settlePayment` is the only writer of a successful payment.
     */
    async verifyWebhook(input: {
      rawBody: Buffer | string;
      headers: Record<string, string | string[] | undefined>;
    }): Promise<WebhookVerification> {
      const header = headerValue(input.headers, PADDLE_SIGNATURE_HEADER);
      if (!header) return { ok: false, reason: "missing_signature" };

      const parsed = parseSignatureHeader(header);
      if (!parsed) return { ok: false, reason: "malformed_signature" };

      // Replay guard FIRST. A captured webhook replayed inside the window still
      // verifies, so the tolerance is the only thing bounding the replay attack;
      // beyond it we refuse before spending a HMAC.
      if (!timestampFresh(parsed.ts)) return { ok: false, reason: "digest_mismatch" };

      const expected = paddleDigest(input.rawBody, c.webhookSecret, parsed.ts);
      if (!digestMatches(expected, parsed.h1)) {
        return { ok: false, reason: "digest_mismatch" };
      }

      let payload: Record<string, unknown>;
      try {
        const text = Buffer.isBuffer(input.rawBody)
          ? input.rawBody.toString("utf8")
          : input.rawBody;
        const parsedBody = JSON.parse(text) as unknown;
        if (!parsedBody || typeof parsedBody !== "object") {
          return { ok: false, reason: "malformed_body" };
        }
        payload = parsedBody as Record<string, unknown>;
      } catch {
        return { ok: false, reason: "malformed_body" };
      }

      const event = decodePaddleEvent(payload);
      if (!event) return { ok: false, reason: "unsupported_event" };
      return { ok: true, event };
    },

    /**
     * NOT SUPPORTED — see the file header. Paddle is a Merchant of Record and
     * exposes no stored card authorization to charge later.
     *
     * Returns a refusal rather than throwing, because the port's contract is
     * `ChargeResult` and a caller that can handle `ok: false` (retry, fall back
     * to a fresh checkout, degrade) should not have to catch. `overage.ts` must
     * check this rather than assume it worked.
     */
    async chargeStoredAuthorization(req: ChargeRequest): Promise<ChargeResult> {
      const reference = buildReference(req.orgId, req.purpose);
      return {
        ok: false,
        reference,
        reason: "stored_authorization_unsupported_by_paddle",
      };
    },

    listEntitlements(reference: string): Promise<StoredEntitlement[]> {
      return entitlementsFor(reference);
    },

    /**
     * Paddle refunds against the ORIGINAL transaction, so it needs the Paddle
     * transaction id — which is not in our `reference` and cannot be added to
     * `RefundRequest` without moving a port contract this file does not own.
     *
     * So it is read back from where settlement already put it: the entitlement
     * envelope on the `PaymentRecord`. The webhook event carries
     * `metadata.paddleTransactionId`; the settling route stores it on an
     * entitlement; `entitlementsFor` reads it here. That keeps the id, the
     * PaymentRecord and the audit envelope consistent with one another instead
     * of inventing a side table that can drift from them.
     *
     * A missing id is a REFUSAL, never a silent no-op: an operator told
     * "refund failed" can retry; an operator told "refunded" who was not cannot.
     */
    async refund(req: RefundRequest): Promise<RefundResult> {
      // Validated for its throw on malformed money even though the amount itself
      // is unused here — Paddle refunds the original transaction, it does not
      // take an amount.
      assertMoney(req.money, "refund.money");

      const transactionId = await paddleTransactionIdFor(req.reference);
      if (transactionId === "") {
        await auditMoney({
          reference: req.reference,
          actor: "gateway:paddle",
          intent: "gateway_refund_no_transaction_id",
          detail: "refund requested for a reference with no stored Paddle transaction id",
          meta: { amountMinor: req.money.amountMinor, currency: req.money.currency },
        });
        return { ok: false, reference: req.reference, reason: "missing_paddle_transaction_id" };
      }

      const res = await paddleRequest(c, "POST", "/transactions", {
        action: "refund",
        transaction_id: transactionId,
        ...(req.reason === undefined ? {} : { reason: req.reason.slice(0, 200) }),
      });
      if (!res.ok) {
        await auditMoney({
          reference: req.reference,
          actor: "gateway:paddle",
          intent: "gateway_refund_failed",
          detail: `Paddle refused the refund: ${res.error}`,
          meta: { transactionId, amountMinor: req.money.amountMinor, currency: req.money.currency },
        });
        return { ok: false, reference: req.reference, reason: res.error };
      }

      // The instruction, not the reversal. `refundPayment` chains what our ledger
      // did; nothing else in the system records that we ASKED the merchant of
      // record to take money back from the customer, which is the act a dispute
      // is argued over.
      await auditMoney({
        reference: req.reference,
        actor: "gateway:paddle",
        intent: "gateway_refund_requested",
        detail: `refund issued against Paddle transaction ${transactionId}`,
        meta: {
          transactionId,
          amountMinor: req.money.amountMinor,
          currency: req.money.currency,
          ...(req.reason === undefined ? {} : { reason: req.reason.slice(0, 200) }),
        },
      });

      // Deliberately does NOT call `refundPayment`. Writing PaymentRecord /
      // ledger state is the settling route's job — it owns the dual-control
      // evidence — and an adapter doing it here would be a second writer.
      return { ok: true, reference: req.reference };
    },
  };
}

/**
 * The Paddle transaction id recorded at settlement time.
 *
 * Returns "" when the reference is unknown or was settled without one — both of
 * which are legitimate states, and both of which must produce a refusal rather
 * than an exception, because this runs on an operator-facing refund path.
 */
export async function paddleTransactionIdFor(reference: string): Promise<string> {
  let entitlements: StoredEntitlement[];
  try {
    entitlements = await entitlementsFor(reference);
  } catch {
    return "";
  }
  for (const e of entitlements) {
    const id = e.metadata?.["paddleTransactionId"];
    if (typeof id === "string" && id !== "") return id;
  }
  return "";
}

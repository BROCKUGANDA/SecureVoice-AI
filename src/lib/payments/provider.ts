import "server-only";
/**
 * `PaymentProvider` port (WP-13).
 *
 * This file is the ONLY place domain code talks to money movement. Nothing
 * outside `src/lib/payments/*` may import a gateway type: no `paystack`,
 * no `flutterwave`, no `authorization_code`, no `x-paystack-signature`. A new
 * gateway is a new adapter file and zero changes to callers — which is the
 * point of the port.
 *
 * ## Contracts that must not move
 *
 *   - **Money is integer minor units.** `Money.amountMinor` is validated at the
 *     port boundary (`assertMoney`), never at the gateway's boundary, so a
 *     float can never enter a `PaymentRecord`.
 *   - **A webhook is a claim, not a fact.** `verifyWebhook` proves the bytes
 *     came from the gateway. It does NOT prove the payment succeeded; the
 *     adapter must re-verify server-side and only then call `settlePayment`.
 *   - **One effect per (reference, eventId).** `settlePayment` is the single
 *     writer of `PaymentRecord` and the single caller of the ledger top-up, and
 *     both are guarded by unique indexes.
 */

import { db } from "@/lib/db";
import { appendInTransaction, refundInTransaction } from "@/lib/billing/ledger";
